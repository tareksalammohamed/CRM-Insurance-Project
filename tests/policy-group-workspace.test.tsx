vi.hoisted(() => { vi.stubEnv('VITE_SUPABASE_URL', 'https://example.supabase.co'); vi.stubEnv('VITE_SUPABASE_ANON_KEY', 'test'); });
import { cleanup, fireEvent, render, screen, waitFor, act } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import type { Policy, Installment } from '../src/lib/supabase';
const mocks = vi.hoisted(() => ({ load: vi.fn(), pay: vi.fn(), cancel: vi.fn() }));
vi.mock('../src/hooks/useAuth', () => ({ useAuth: () => ({ user: { id: 'u' } }) }));
vi.mock('../src/lib/branchContext', () => ({ useBranchContext: () => ({ currentBranchId: 'branch' }) }));
vi.mock('../src/lib/notify', () => ({ useNotify: () => ({ error: vi.fn() }) }));
vi.mock('../src/pages/Policies/services/policyGroupService', () => ({ fetchPolicyGroup: mocks.load }));
vi.mock('../src/features/installments/installmentsService', () => ({ payInstallment: mocks.pay, cancelInstallmentPayment: mocks.cancel }));
import { PolicyGroupMembersDialog } from '../src/pages/Policies/components/dialogs/PolicyGroupMembersDialog';
const a = { id: 'a', policy_number: '7010001', customer_id: 'c', owner_id: 'u', policy_type: 'protection_investment', start_date: '2026-01-01', created_at: '2026-01-02', premium_amount: 100, sum_assured: 50000, status: 'active', payment_method: 'monthly', notes: 'ملاحظة الأولى', customer: { name: 'عميل المجموعة', phone: '01012345678' }, owner: { name: 'الوكيل' } } as Policy;
const b = { ...a, id: 'b', policy_number: '7010002', notes: 'ملاحظة الثانية' } as Policy;
const rows = [ { id: 'i1', policy_id: 'a', installment_number: 1, status: 'paid', amount: 111, due_date: '2026-01-01', paid_at: '2026-01-01' }, { id: 'i2', policy_id: 'b', installment_number: 1, status: 'pending', amount: 222, due_date: '2026-01-01' } ] as Installment[];
const data = { policies: [a, b], installments: rows };
afterEach(cleanup);
beforeEach(() => { vi.clearAllMocks(); mocks.load.mockResolvedValue(data); mocks.pay.mockResolvedValue(undefined); mocks.cancel.mockResolvedValue({}); });
it('shows the complete group with shared data once and differing fields per policy, without navigation', async () => {
  const open = vi.fn();
  render(<PolicyGroupMembersDialog members={[a]} onClose={vi.fn()} onOpenDetails={open} />);
  await screen.findByText('عميل المجموعة');
  expect(screen.getAllByText('عميل المجموعة')).toHaveLength(1);
  expect(screen.getByText('7010001', { selector: 'bdi' })).toBeTruthy(); expect(screen.getByText('7010002', { selector: 'bdi' })).toBeTruthy();
  expect(screen.getAllByText('شهري')).toHaveLength(1);
  expect(screen.getByText('إجمالي القسط الصافي لكل دفعة')).toBeTruthy();
  expect(screen.getByText('ملاحظات: ملاحظة الأولى')).toBeTruthy(); expect(screen.getByText('ملاحظات: ملاحظة الثانية')).toBeTruthy();
  expect(screen.getAllByRole('group').filter(node => node.tagName === 'DETAILS').every(node => node.hasAttribute('open'))).toBe(true);
  expect(open).not.toHaveBeenCalled();
  expect(mocks.load).toHaveBeenCalledWith(a, 'branch');
});
it('pays the exact installment through the existing shared action and refreshes the group', async () => {
  const changed = vi.fn();
  render(<PolicyGroupMembersDialog members={[a,b]} onClose={vi.fn()} onOpenDetails={vi.fn()} onChanged={changed} />);
  await screen.findByText('7010002', { selector: 'bdi' });
  fireEvent.click(screen.getAllByRole('button', { name: 'سداد القسط رقم 1' })[0]);
  const buttons = screen.getAllByRole('button');
  const confirm = buttons.find(button => button.textContent?.includes('تأكيد السداد'));
  expect(confirm).toBeTruthy();
  fireEvent.click(confirm!);
  await waitFor(() => expect(mocks.pay).toHaveBeenCalledOnce());
  expect(mocks.pay.mock.calls[0][0]).toEqual(rows[1]);
  expect(changed).toHaveBeenCalledOnce();
  await waitFor(() => expect(mocks.load).toHaveBeenCalledTimes(2));
});
it('does not publish partial totals when loading fails', async () => {
  mocks.load.mockRejectedValueOnce(new Error('failed'));
  render(<PolicyGroupMembersDialog members={[a,b]} onClose={vi.fn()} onOpenDetails={vi.fn()} />);
  await screen.findByText('تعذر تحميل المجموعة كاملة. أعد المحاولة لعرض تفاصيلها ومجاميعها.');
  expect(screen.queryByLabelText('ملخص المجموعة')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'إعادة المحاولة' }));
  await screen.findByText('عميل المجموعة');
});
it('ignores an old group response after switching to another group', async () => {
  let resolve!: (value: typeof data) => void;
  mocks.load.mockReturnValueOnce(new Promise(done => { resolve = done; }));
  const props = { onClose: vi.fn(), onOpenDetails: vi.fn() };
  const view = render(<PolicyGroupMembersDialog members={[a]} {...props} />);
  const other = { ...b, id: 'other', policy_number: '9990001', customer_id: 'other' };
  mocks.load.mockResolvedValueOnce({ policies: [other], installments: [] });
  view.rerender(<PolicyGroupMembersDialog members={[other]} {...props} />);
  await screen.findByText('9990001', { selector: 'bdi' });
  await act(async () => resolve(data));
  expect(screen.queryByText('7010001')).toBeNull();
});
