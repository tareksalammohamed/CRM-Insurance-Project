import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ clock: vi.fn(), raw: vi.fn(), list: vi.fn(), quick: vi.fn(), user: { id: 'u', role: 'agent', name: 'Test', target: 10000 } }));
vi.mock('../src/features/closingExtensions/operationalMonthService', () => ({ fetchOperationalMonth: mocks.clock }));
vi.mock('../src/hooks/useAuth', () => ({ useAuth: () => ({ user: mocks.user }) }));
vi.mock('../src/lib/branchContext', () => ({ useBranchContext: () => ({ currentBranchId: null }) }));
vi.mock('../src/hooks/useReconnectRefetch', () => ({ useReconnectRefetch: vi.fn() }));
vi.mock('../src/pages/Dashboard/services/dashboardService', () => ({ fetchDashboardScope: async () => ({ data: ['u'], status: 'online' }), fetchDashboardRawData: mocks.raw, fetchTeamUsers: async () => [], fetchDashboardBranchRoles: async () => new Map() }));
vi.mock('../src/pages/Cancellations/services/cancellationService', () => ({ loadCancellationSummary: async () => ({ cancellationRate: 0, cancelledValue: 0 }) }));
vi.mock('../src/features/customerFollowup/FollowupPanel', () => ({ PromiseDialog: () => null, FollowupWorkspaceButton: () => null }));
vi.mock('../src/features/installments/PayInstallmentModal', () => ({ PayInstallmentModal: () => null }));
vi.mock('../src/features/installments/CancelInstallmentModal', () => ({ CancelInstallmentModal: () => null }));
vi.mock('../src/pages/Collection/hooks/useTeamMembers', () => ({ useTeamMembers: () => [] }));
vi.mock('../src/pages/Collection/hooks/useCollectionMaintenance', () => ({ useCollectionMaintenance: () => async () => {} }));
vi.mock('../src/pages/Collection/hooks/useCollectionInstallments', () => ({ useCollectionInstallments: mocks.list }));
vi.mock('../src/pages/Collection/hooks/useCollectionQuickStats', () => ({ useCollectionQuickStats: mocks.quick }));
vi.mock('../src/pages/Collection/hooks/usePolicyInstallmentsModal', () => ({ usePolicyInstallmentsModal: () => ({}) }));
vi.mock('../src/pages/Collection/hooks/useInstallmentPaymentActions', () => ({ useInstallmentPaymentActions: () => ({}) }));
import { useDashboard } from '../src/pages/Dashboard/hooks/useDashboard';
import { Collection } from '../src/pages/Collection';
let client: QueryClient;
const wrapper = ({ children }: { children: ReactNode }) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
const period = { reporting_month: '2026-10-01', calendar_month: '2026-11-01', cairo_date: '2026-11-01', extended_until: '2026-11-01', server_now: '2026-11-01T12:00:00Z', valid_until: '2026-11-01T22:00:00Z', expiresAt: Date.now() + 60_000 };
beforeEach(() => {
  vi.resetAllMocks(); client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 } } });
  mocks.raw.mockResolvedValue({ customersRes: { data: [], count: 0 }, policiesRes: { data: [] }, installmentsRes: { data: [] }, paymentsRes: { data: [] } });
  mocks.list.mockReturnValue({ installments: [], loading: false, isInitialLoading: false, page: 1, setPage: () => {}, totalPages: 1, totalCount: 0, searchQuery: '', localSearch: '', setLocalSearch: () => {}, loadInstallments: async () => {} });
  mocks.quick.mockReturnValue({ quickStats: null, quickStatsLoading: false, loadQuickStats: async () => {} });
});
afterEach(() => { cleanup(); client.clear(); });
it('waits for the confirmed company month before dashboard financial reads and uses October during extension', async () => {
  let resolve!: (value: typeof period) => void;
  mocks.clock.mockReturnValue(new Promise(done => { resolve = done; }));
  const { result } = renderHook(useDashboard, { wrapper });
  expect(mocks.raw).not.toHaveBeenCalled();
  await act(async () => resolve(period));
  await waitFor(() => expect(mocks.raw).toHaveBeenCalled());
  expect(mocks.raw.mock.calls[0][1]).toBe('2026-10-01');
  expect(result.current.selectedMonth.getMonth()).toBe(9); expect(result.current.isCurrentMonth).toBe(true);
});
it('passes the same held month to collection lists and summary cards after confirmation', async () => {
  mocks.clock.mockResolvedValue(period);
  render(<QueryClientProvider client={client}><MemoryRouter initialEntries={['/collection']}><Collection /></MemoryRouter></QueryClientProvider>);
  await waitFor(() => expect(mocks.list.mock.calls.at(-1)?.[0].yearMode).toBe('year1'));
  expect(mocks.list.mock.calls.at(-1)?.[0].monthStart).toBe('2026-10-01');
  expect(mocks.quick.mock.calls.at(-1)?.[4]).toBe('2026-10-01');
  expect(mocks.quick.mock.calls.at(-1)?.[5]).toBe(true);
  expect(screen.getByText('متابعة الأقساط والتحصيلات — أكتوبر 2026')).toBeTruthy();
});
it('retains an explicit historical collection link instead of silently replacing its scope', async () => {
  mocks.clock.mockResolvedValue(period);
  render(<QueryClientProvider client={client}><MemoryRouter initialEntries={['/collection?month=2026-09-01&quickFilter=paid']}><Collection /></MemoryRouter></QueryClientProvider>);
  await waitFor(() => expect(mocks.list.mock.calls.at(-1)?.[0].yearMode).toBe('year1'));
  expect(mocks.list.mock.calls.at(-1)?.[0].monthStart).toBe('2026-09-01');
  expect(mocks.list.mock.calls.at(-1)?.[0].quickFilter).toBe('paid');
  expect(screen.getByText('متابعة الأقساط والتحصيلات — سبتمبر 2026')).toBeTruthy();
});
